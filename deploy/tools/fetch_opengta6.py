#!/usr/bin/env python3
"""Build webapp/opengta6.js from Open GTA 6 Map (github.com/fbritoferreira/gta6) — CC BY 4.0.
Their map units convert to game coordinates (same as gtadb / our map): gx = x*32 - 16384, gy = 16384 - y*32.
Usage: python3 deploy/tools/fetch_opengta6.py"""
import json, urllib.request
from pathlib import Path
BASE = "https://fbritoferreira.github.io/gta6/data/"
get = lambda f: json.loads(urllib.request.urlopen(urllib.request.Request(BASE + f, headers={"User-Agent": "Mozilla/5.0 (fan-tracker)"}), timeout=60).read())
locs, cats = get("locations.json"), get("categories.json")
removed = {r.get("id") for r in (get("removed.json") if True else [])} if True else set()
GROUP = {
  "rob":   "safe towatm store smash fence bank payday gang",
  "coll":  "card package waink magazine meteorite streetart bookswap playlist bottle treasure mural flamingo",
  "race":  "stunt bridge knife basejump race drone",
  "act":   "event hoop arcade fishing range meditation hunting leisure",
  "veh":   "vehicle",
  "wep":   "weapon",
  "shop":  "shop food",
  "place": "transport building civic safehouse other",
}
kind2g = {k: g for g, ks in GROUP.items() for k in ks.split()}
names = {k["key"]: k["name"] for k in cats["kinds"]}
pins = []
for l in locs:
    if l.get("id") in removed: continue
    gx, gy = round(l["x"] * 32 - 16384), round(16384 - l["y"] * 32)
    label = l.get("type") or names.get(l["kind"], l["kind"])
    desc = " ".join(x for x in [l.get("description") or "", f"Area: {l['area']}." if l.get("area") else ""] if x)
    pins.append([l.get("name") or label, label, gx, gy, kind2g.get(l["kind"], "place"), desc, l.get("id", ""), "o"])
out = Path(__file__).resolve().parents[2] / "webapp" / "opengta6.js"
out.write_text("// Open GTA 6 Map — https://github.com/fbritoferreira/gta6 — CC BY 4.0 (\"Map data from Open GTA 6 Map (fbritoferreira), CC BY 4.0\").\n"
  "// Generated by deploy/tools/fetch_opengta6.py; converted to game coordinates. [name, type, x, y, group, description, id, source]\n"
  "window.OPENGTA6 = " + json.dumps({"pins": pins}, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(f"{len(pins)} pins → {out} ({out.stat().st_size // 1024} KB)")
