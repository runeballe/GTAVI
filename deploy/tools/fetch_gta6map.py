#!/usr/bin/env python3
"""Build webapp/community.js from gta6map.io's public map bundle (robots.txt allows all).
Pins use the same game coordinates as gtadb.org, so they drop straight onto our map.
The output is NOT committed to git (third-party descriptions) — build.sh copies it if present.
Usage: python3 deploy/tools/fetch_gta6map.py"""
import json, re, sys, urllib.request
from pathlib import Path
UA = {"User-Agent": "Mozilla/5.0 (fan-tracker)"}
get = lambda u: urllib.request.urlopen(urllib.request.Request(u, headers=UA), timeout=60).read().decode("utf-8", "replace")
home = get("https://gta6map.io/")
chunks = sorted(set(re.findall(r'/_next/static/chunks/[^"]+\.js', home)))
pat = re.compile(r'\{"id":"([a-z0-9]{6,10})","name":"((?:[^"\\]|\\.)*)","category":"([a-z0-9-]+)","x":(-?[\d.]+),"y":(-?[\d.]+)(?:,"description":"((?:[^"\\]|\\.)*)")?')
un = lambda t: (t or "").replace("\\'", "'").replace('\\"', '"').replace("\\n", " ").replace("\\\\", "\\")
pins = {}
for c in chunks:
    js = get("https://gta6map.io" + c)
    for m in pat.finditer(js):
        pins[m[1]] = [un(m[2]), m[3], round(float(m[4])), round(float(m[5])), un(m[6])]
if len(pins) < 500: sys.exit(f"only {len(pins)} pins found — site layout changed?")
GROUPS = {
  "rob":   ("Robberies",          "#ff5f5f", "smash-n-grab safe bank big-bank payday-loan gang-operation gang-compound fence convenience-store liquor-store"),
  "coll":  ("Collectibles",       "#b388ff", "collectible-card card-* magazine book-swap playlist waink-* hidden-package mural"),
  "race":  ("Races & stunts",     "#00d9ff", "race drone-race stunt-jump flight-stunt base-jump"),
  "act":   ("Activities",         "#2ecc71", "arcade pool golf basketball shooting-range gym fishing random-event nightclub cinema"),
  "veh":   ("Vehicles",           "#ffd60a", "standout-vehicle vehicle-request-randy vehicle-request-moses pay-n-spray vehicle-mod-shop garage vehicle-rental car-wash gas-station ev-charger marina"),
  "wep":   ("Weapons",            "#ff9f1a", "unique-weapon ammu-nation-*"),
  "shop":  ("Shops & services",   "#9aa4b5", "atm street-food bar cafe-takeout food-and-drink souvenir-swimwear haircut footwear electronics tattoo sportswear formal casual-street thrift"),
  "place": ("Places & transport", "#7fd1c7", "landmark city-town bus-stop train-station public-transport ferry-terminal safehouse police-station fire-station hospital"),
}
def group_of(cat):
    for g, (_, _, cats) in GROUPS.items():
        for p in cats.split():
            if cat == p or (p.endswith("*") and cat.startswith(p[:-1])): return g
    return "place"
data = {"source": "gta6map.io", "groups": {g: [n, col] for g, (n, col, _) in GROUPS.items()},
        "pins": [[*v[:4], group_of(v[1]), v[4]] for v in pins.values()]}
out = Path(__file__).resolve().parents[2] / "webapp" / "community.js"
out.write_text("// Community map pins from gta6map.io (generated by deploy/tools/fetch_gta6map.py — not in git). [name, category, x, y, group, description]\nwindow.COMMUNITY = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(f"{len(pins)} pins → {out} ({out.stat().st_size // 1024} KB)")
